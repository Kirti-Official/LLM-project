
import json
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]

RAW_FILE = (
    PROJECT_ROOT / "data" / "raw" / "ramdocs_test.jsonl"
)

SCREENED_FILE = (
    PROJECT_ROOT / "data" / "processed" / "ramdocs_screened.jsonl"
)

OUTPUT_FILE = (
    PROJECT_ROOT / "data" / "processed"
    / "ramdocs_screened_with_answers.jsonl"
)


def load_jsonl(file_path):
    records = []

    with open(file_path, "r", encoding="utf-8") as file:
        for line in file:
            if line.strip():
                records.append(json.loads(line))

    return records


def save_jsonl(records, file_path):
    file_path.parent.mkdir(parents=True, exist_ok=True)

    with open(file_path, "w", encoding="utf-8") as file:
        for record in records:
            file.write(json.dumps(record, ensure_ascii=False) + "\n")


def main():
    print("=" * 65)
    print("VERDICT - Restoring Answer Annotations")
    print("=" * 65)

    raw_records = load_jsonl(RAW_FILE)
    screened_records = load_jsonl(SCREENED_FILE)

    if len(raw_records) != len(screened_records):
        raise ValueError(
            f"Record count mismatch: raw={len(raw_records)}, "
            f"screened={len(screened_records)}"
        )

    enriched_records = []

    for index, (raw, screened) in enumerate(
        zip(raw_records, screened_records)
    ):
        if raw["question"].strip() != screened["question"].strip():
            raise ValueError(
                f"Question mismatch at record {index}. "
                "Cannot safely match annotations by order."
            )

        enriched = dict(screened)

        # Ground-truth annotations: evaluation only.
        enriched["gold_answers"] = raw.get("gold_answers", [])
        enriched["wrong_answers"] = raw.get("wrong_answers", [])

        # Candidate answer will be generated by the model later.
        # Do not populate this from gold_answers during inference.
        enriched["candidate_answer"] = None
        enriched["candidate_answer_source"] = "not_generated"

        enriched_records.append(enriched)

    save_jsonl(enriched_records, OUTPUT_FILE)

    print("\nANNOTATION RESTORATION")
    print("-" * 65)
    print("Raw records:", len(raw_records))
    print("Screened records:", len(screened_records))
    print("Enriched records:", len(enriched_records))

    print("\nFIRST RECORD CHECK")
    first = enriched_records[0]

    print("Question:", first["question"])
    print("Gold answers:", first["gold_answers"])
    print("Wrong answers:", first["wrong_answers"])
    print("Candidate answer:", first["candidate_answer"])
    print("Candidate source:", first["candidate_answer_source"])

    print("\nOutput file:")
    print(OUTPUT_FILE)

    print("\nAnnotation restoration completed successfully!")


if __name__ == "__main__":
    main()
